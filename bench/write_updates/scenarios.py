TOPICS = list(MEMORIES)


def body(topic: str) -> str:
    return " ".join(MEMORIES[topic][1])


def clue_vid(topic: str) -> int:
    return 400 + 17 * TOPICS.index(topic)


@dataclass(frozen=True, slots=True)
class Scenario:
    sid: str
    topic: str  # the memory the user asks about (always shown)
    fact: str  # what the user says
    statement: int | None  # index of the outdated statement (None = control)
    key: str | None  # the phrase a correct old_span must contain

    @property
    def is_update(self) -> bool:
        return self.statement is not None

    @property
    def gold_statement(self) -> str | None:
        return None if self.statement is None else MEMORIES[self.topic][1][self.statement]


