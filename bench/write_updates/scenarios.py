def shown_topics(s: Scenario) -> list[str]:
    """The query's hits: the scenario's memory plus two deterministic distractors; the memory is
    first or second (alternating) so position is no cue."""
    i = TOPICS.index(s.topic)
    others = [TOPICS[(i + 3) % len(TOPICS)], TOPICS[(i + 7) % len(TOPICS)]]
    n = int(s.sid[1:])
    return [others[0], s.topic, others[1]] if n % 2 else [s.topic, *others]


def query_result(s: Scenario) -> dict:
    """A ``memory.query`` result in the server's shape (card, hits with chunk clues, budget)."""
    hits = []
    for rank, topic in enumerate(shown_topics(s)):
        title, _st = MEMORIES[topic]
        hits.append(
            {
                "clue": f"v{clue_vid(topic)}.0",
                "kind": "fact",
                "title": title,
                "preview": body(topic),
                "score": round(0.0331 - 0.0017 * rank, 4),
                "valid_from": "2026-08-14T09:12:00.000000Z",
                "tags": [],
                "device_scope": "all",
            }
        )
    return {
        "contract_version": "query/2",
        "project": "acme-api",
        "card": {"clue": "v12", "text": "acme-api: the ACME customer API (Python, Postgres)."},
        "hits": hits,
        "evidence": "matched",
        "budget": {"limit": 2000, "used": 431, "tokenizer": "o200k_base"},
    }


